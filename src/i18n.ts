const catalogs = { bn, en, hi }
let fallback: Locale = 'bn'
const languageKey = 'orbis-maya-language-v1'
export function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(languageKey)
    if (saved === 'bn' || saved === 'en' || saved === 'hi') return saved
  } catch { /* Language preference remains usable without storage. */ }
  return fallback
}
export function setLocale(locale: Locale) {
  fallback = locale
  try { localStorage.setItem(languageKey, locale) } catch { /* Device storage may be unavailable. */ }
  window.dispatchEvent(new Event('maya-language'))
}
function subscribe(listener: () => void) {
  window.addEventListener('storage', listener)
  window.addEventListener('maya-language', listener)
  return () => {
    window.removeEventListener('storage', listener)
    window.removeEventListener('maya-language', listener)
  }
}
export function useLocale() { return useSyncExternalStore(subscribe, readLocale) }
export function text(locale: Locale, key: keyof typeof bn): string { return catalogs[locale][key] }
